"""Write compositions/m-brand.html - the brand corner logo overlay - timed from film.json, drawn from brand.json.

usage (film root): <py> <skill>/scripts/build-brand.py
Reads ./film.json and ./brand.json (name, wordmark, logo_has_text; logo file = assets/brand/logo.png or logo.svg).
In 0.2s after the first scene ends (s01 opens on the full logo), out 2.7s after the last scene starts (the end card
shows the logo big with the CTA). Landscape: top-right corner; vertical: top-centre above the Reels UI.
film.json must list it: "overlays": [..., {"id": "m-brand", "track": 3, "z": 6}].
"""
import json
from html import escape
from pathlib import Path

f = json.loads(Path("film.json").read_text(encoding="utf-8"))
b = json.loads(Path("brand.json").read_text(encoding="utf-8"))
name = b["name"]
wm = b.get("wordmark")
if not wm:
    parts = name.split(None, 1)
    wm = parts if len(parts) == 2 else [name]
logo = next((n for n in ("logo.png", "logo.svg") if Path("assets/brand", n).is_file()), None)
inner = f'<img src="assets/brand/{logo}" alt="">' if logo else ""
if not (b.get("logo_has_text") and logo):
    gap = " " if len(wm) > 1 and f"{wm[0]} {wm[1]}" in name else ""  # "Sample Studio" keeps its space, "BrandCo" stays one word
    inner += f"<b>{escape(wm[0])}{gap}<i>{escape(wm[1])}</i></b>" if len(wm) > 1 else f"<b>{escape(wm[0])}</b>"
logo_html = f'<div class="kit-logo" style="--h:56px">{inner}</div>'

W, H = f["width"], f["height"]
durs = [s[1] * 60 / f["bpm"] * f.get("beats_per_bar", 4) for s in f["scenes"]]
total = round(sum(durs), 4)
t_in = round(durs[0] + 0.2, 2)
t_out = round(total - durs[-1] + 2.7, 2)
pos = "right: 52px; top: 44px;" if W > H else "left: 50%; top: 96px; margin-left: -150px;"
html = f"""<!-- Generated by kape-explainer/scripts/build-brand.py from film.json + brand.json - corner logo for the whole film.
     In {t_in}s (after s01's full logo), out {t_out}s (before the end card's big logo + CTA). -->
<template>
<link rel="stylesheet" href="assets/kit.css">
<style>
#root {{ position: absolute; inset: 0; width: {W}px; height: {H}px; overflow: hidden; }}
#m-brand-bug {{ position: absolute; {pos} padding: 14px 24px 14px 18px; border-radius: 22px;
  background: rgba(255,255,255,.88); box-shadow: 0 2px 4px rgba(11,30,63,.06), 0 12px 28px rgba(11,30,63,.10); opacity: 0; will-change: transform, opacity; }}
</style>
<div id="root" data-composition-id="m-brand" data-width="{W}" data-height="{H}">
  <div id="m-brand-layer" class="clip" data-start="0" data-duration="{total}" data-track-index="1" style="position:absolute; inset:0;">
    <div id="m-brand-bug">{logo_html}</div>
  </div>
</div>
<script>
(function () {{
  var tl = gsap.timeline({{ paused: true }});
  tl.fromTo('#m-brand-bug', {{ opacity: 0, y: -16 }}, {{ opacity: 1, y: 0, duration: 0.6, ease: 'expo.out', force3D: true }}, {t_in});
  tl.fromTo('#m-brand-bug', {{ opacity: 1, y: 0 }}, {{ opacity: 0, y: -16, duration: 0.4, ease: 'power2.in', immediateRender: false, force3D: true }}, {t_out});
  window.__timelines = window.__timelines || {{}};
  window.__timelines['m-brand'] = tl;
}})();
</script>
</template>
"""
Path("compositions").mkdir(exist_ok=True)
Path("compositions/m-brand.html").write_text(html, encoding="utf-8")
print(f"compositions/m-brand.html: in {t_in}s, out {t_out}s, total {total}s ({W}x{H})")
